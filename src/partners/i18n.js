/**
 * Язык браузера → язык портала. Малайский (ms) — не наш язык: в Малайзии по умолчанию
 * английский, индонезийский доступен в переключателе.
 */
export function pickLang(candidates = []) {
  const map = { en: 'en', pt: 'pt', es: 'es', vi: 'vi', id: 'id', in: 'id', fil: 'fil', tl: 'fil', ru: 'ru' }
  for (const c of candidates) {
    const base = String(c || '').toLowerCase().split(/[-_]/)[0]
    if (map[base]) return map[base]
  }
  return 'en'
}

