export const STRINGS = { en, pt, es, vi, id, fil, ru }

/** Перевод с подстановкой {параметров}; недостающий ключ берётся из английского. */
export function translator(lang) {
  const dict = STRINGS[lang] || en
  return (key, params = {}) => String(dict[key] ?? en[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`))
}
