export const closeupFor = (bodyId, regionId) => CLOSEUPS[`${bodyId}:${regionId}`] || null

export const CODEX_TOTAL = Object.values(CLOSEUPS).reduce((n, c) => n + c.objects.length, 0)

// ---------------- Кодекс: что игрок уже осмотрел ----------------
const CODEX_KEY = 'wt-cosmos-codex'
export function loadCodex() {
  try { return new Set(JSON.parse(localStorage.getItem(CODEX_KEY) || '[]')) } catch { return new Set() }
}
export function discover(key) {
  const set = loadCodex()
  const isNew = !set.has(key)
  if (isNew) {
    set.add(key)
    try { localStorage.setItem(CODEX_KEY, JSON.stringify([...set])) } catch { /* приватный режим */ }
  }
  return { isNew, count: set.size, total: CODEX_TOTAL }
}
